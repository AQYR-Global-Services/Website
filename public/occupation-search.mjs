const byCode = new Map(occupations.map(row => [row.code,row]));
export function getOccupation(code) { return byCode.get(String(code || '')) || null; }
export function normaliseOccupationQuery(value) {
  return String(value || '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu,' ').trim();
}
const indexed = occupations.map(row => {
  let zh = chinese[row.code] || '';
  if (row.code.startsWith('2544')) zh += ' 注册护士 护士 护理';
  return {...row, search:normaliseOccupationQuery([row.code,row.title,...row.aliases,zh].join(' ')), titleKey:normaliseOccupationQuery(row.title), zh};
});
export function searchOccupations(query, limit = 12) {
  const key = normaliseOccupationQuery(query);
  if (!key || (!/[\u3400-\u9fff]/u.test(key) && key.length < 2)) return {matches:[],total:0};
  const tokens = key.split(/\s+/);
  const results = indexed.filter(row => row.code.startsWith(key) || tokens.every(token=>row.search.includes(token)));
  const rank = row => row.code === key ? 0 : row.titleKey === key ? 1 : row.code.startsWith(key) ? 2 : row.titleKey.startsWith(key) ? 3 : 4;
  results.sort((a,b)=>rank(a)-rank(b) || a.title.localeCompare(b.title) || a.code.localeCompare(b.code));
  return {matches:results.slice(0,limit),total:results.length};
}
